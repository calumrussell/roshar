"""Generate tests/vectors.json from the official Lighter Python SDK's signer library.

Run with the lighter-sdk virtualenv (any env with `lighter-sdk` installed):

    python tests/gen_vectors.py > tests/vectors.json

No network: the Go signer is created with an unroutable URL, and every transaction is given an
explicit nonce, so it never calls Lighter. The API key is a fresh random throwaway key generated by
the library itself.

The Go signer fills two inputs from its own clock: `ExpiredAt` (now + 10 min - 1 s) and, for an
order expiry of -1, `OrderExpiry`. Both are recorded through the returned tx_info. The Schnorr nonce
is random, so the signature cannot be reproduced from the inputs alone; the Rust tests recover it
from the recorded signature and the private key (k = s + e*sk) and check that signing with it gives
the same bytes. See src/signer.rs.
"""

import ctypes
import json
import sys
import time
from importlib import metadata

from lighter import signer_client as sc

lib = sc.get_signer()


def s(ptr):
    return sc.decode_and_free(ptr)


def tx(res):
    err = s(res.err)
    info = s(res.txInfo)
    h = s(res.txHash)
    s(res.messageToSign)
    if err:
        raise RuntimeError(err)
    return {"tx_type": res.txType, "tx_info": info, "tx_hash": h}


key = lib.GenerateAPIKey()
priv, pub, err = s(key.privateKey), s(key.publicKey), s(key.err)
assert err is None, err

ACCOUNT = 281474976710 // 7  # arbitrary, > 0
KEY_INDEX = 4
out = {
    "source": f"lighter-sdk {metadata.version('lighter-sdk')} shared signer library",
    "generated_at_ms": int(time.time() * 1000),
    "private_key": priv,
    "public_key": pub,
    "account_index": ACCOUNT,
    "api_key_index": KEY_INDEX,
    "chains": {},
}

for chain_id in (304, 300):
    e = lib.CreateClient(b"http://127.0.0.1:9", priv[2:].encode(), chain_id, KEY_INDEX, ACCOUNT)
    assert s(e) is None
    c = {"create_order": [], "cancel_order": [], "cancel_all_orders": [], "modify_order": [], "auth_token": []}
    # (market, coi, base, price, is_ask, type, tif, reduce_only, trigger, expiry, nonce)
    orders = [
        (45, 1763200000001, 3500, 1234, 0, 0, 2, 0, 0, 1763200330000, 17),  # post-only limit buy (fillgen create)
        (2, 1763200000002, 70, 182345, 1, 0, 2, 0, 0, 1763200330000, 18),  # post-only limit sell
        (45, 1763200000003, 52000, 1199, 1, 1, 0, 1, 0, 0, 19),  # reduce-only IOC market sell (fillgen hedge)
        (1, 0, 1, 1, 0, 0, 1, 0, 0, -1, 0),  # GTT limit, default 28-day expiry filled in by the library
        (0, 281474976710655, 2**47, 2**32 - 1, 1, 0, 0, 0, 0, 0, 2**47),  # IOC limit, large values
    ]
    for o in orders:
        for rep in range(2):
            r = tx(lib.SignCreateOrder(*o[:10], 0, 0, 0, 0, 0, 0, o[10], KEY_INDEX, ACCOUNT))
            c["create_order"].append({
                "market_index": o[0], "client_order_index": o[1], "base_amount": o[2], "price": o[3],
                "is_ask": o[4], "order_type": o[5], "time_in_force": o[6], "reduce_only": o[7],
                "trigger_price": o[8], "order_expiry_arg": o[9], "nonce": o[10], **r,
            })
    for (m, idx, nonce) in [(45, 1763200000001, 20), (2, 281474976710655, 21)]:
        for rep in range(2):
            r = tx(lib.SignCancelOrder(m, idx, 0, nonce, KEY_INDEX, ACCOUNT))
            c["cancel_order"].append({"market_index": m, "index": idx, "nonce": nonce, **r})
    for (tif, t, m, nonce) in [(0, 0, 45, 22), (0, 0, 255, 23), (1, 1763200600000, 255, 24), (2, 0, 255, 25)]:
        for rep in range(2):
            r = tx(lib.SignCancelAllOrders(tif, t, m, 0, nonce, KEY_INDEX, ACCOUNT))
            c["cancel_all_orders"].append({"time_in_force": tif, "time": t, "market_index": m, "nonce": nonce, **r})
    for (m, idx, base, price, trig, nonce) in [(45, 1763200000001, 7000, 1235, 0, 26), (2, 99, 1, 1, 0, 27)]:
        for rep in range(2):
            r = tx(lib.SignModifyOrder(m, idx, base, price, trig, 0, 0, 0, 0, 0, 0, nonce, 0, KEY_INDEX, ACCOUNT))
            c["modify_order"].append({"market_index": m, "index": idx, "base_amount": base, "price": price,
                                      "trigger_price": trig, "nonce": nonce, **r})
    for deadline in (1763229000, 1893456000):
        for rep in range(2):
            res = lib.CreateAuthToken(deadline, KEY_INDEX, ACCOUNT)
            tok, err = s(res.str), s(res.err)
            assert err is None, err
            c["auth_token"].append({"deadline": deadline, "token": tok})
    out["chains"][str(chain_id)] = c

json.dump(out, sys.stdout, indent=1)
sys.stdout.write("\n")
