"""Signing vectors for trigger orders (TP/SL, `normalTpsl` / `positionTpsl` grouping) and
`updateLeverage`, generated by the official hyperliquid-python-sdk (tested with 0.24.0).

Offline only: the SDK's HTTP client is patched to raise, and `Exchange._post_action` is replaced with a
capture of (action, signature, nonce). Nothing is ever sent. The key is a throwaway.

    <venv with hyperliquid-python-sdk>/bin/python -I tests/gen_trigger_vectors.py > tests/trigger_vectors.json

Each case is built through the SDK's own `Exchange` methods (`bulk_orders`, `update_leverage`), so the
action dict, float_to_wire and key order are the SDK's, not a re-implementation.
"""
from __future__ import annotations

import importlib.metadata
import json
import sys

import eth_account
import hyperliquid.api
import hyperliquid.exchange
from hyperliquid.exchange import Exchange
from hyperliquid.utils import constants
from hyperliquid.utils.signing import action_hash
from hyperliquid.utils.types import Cloid

KEY = "0x4c0883a69102937d6231471b5dbb6204fe5129617082792ae468d01a3f362318"  # same throwaway as vectors.json
VAULT = "0x1f1f1f1f1f1f1f1f1f1f1f1f1f1f1f1f1f1f1f1f"
NONCE = 1793200000000


def _no_network(self, url_path, payload=None):
    raise RuntimeError(f"network disabled in vector generation: {url_path}")


hyperliquid.api.API.post = _no_network

# Perp universe: asset i is "C{i}" except a few named coins at fixed indices.
NAMED = {0: ("BTC", 5), 1: ("ETH", 4), 5: ("SOL", 2), 159: ("HYPE", 2), 173: ("PUMP", 0)}
META = {
    "universe": [
        {"name": NAMED.get(i, (f"C{i}", 2))[0], "szDecimals": NAMED.get(i, (f"C{i}", 2))[1]}
        for i in range(200)
    ]
}
SPOT_META = {"universe": [], "tokens": []}

captured: list = []


def _capture(self, action, signature, nonce):
    captured.append((action, signature, nonce))
    return {"status": "ok", "response": {"type": "default"}}


Exchange._post_action = _capture
hyperliquid.exchange.get_timestamp_ms = lambda: NONCE


def exchange(mainnet: bool, vault: str | None) -> Exchange:
    url = constants.MAINNET_API_URL if mainnet else constants.TESTNET_API_URL
    return Exchange(eth_account.Account.from_key(KEY), url, meta=META, vault_address=vault, spot_meta=SPOT_META)


def trig(px: float, is_market: bool, tpsl: str) -> dict:
    return {"trigger": {"triggerPx": px, "isMarket": is_market, "tpsl": tpsl}}


# name -> (description, callable(ex))
CASES = {
    # Exactly spike-short's place_stop (src/spike/exec/hl_client.py): reduce-only stop-market buy on a
    # short, limit = trigger * (1 + ioc_slippage) rounded, grouping positionTpsl, no cloid.
    "stop_market_position_tpsl": (
        "szeth stop: reduce-only stop-market buy, tpsl sl, grouping positionTpsl",
        lambda ex: ex.bulk_orders(
            [{"coin": "HYPE", "is_buy": True, "sz": 12.34, "limit_px": 41.814,
              "order_type": trig(41.4, True, "sl"), "reduce_only": True}],
            grouping="positionTpsl",
        ),
    ),
    "stop_limit": (
        "stop-limit sell (isMarket false), cloid, grouping na",
        lambda ex: ex.bulk_orders(
            [{"coin": "ETH", "is_buy": False, "sz": 0.5, "limit_px": 3150.5,
              "order_type": trig(3160.0, False, "sl"), "reduce_only": True,
              "cloid": Cloid.from_str("0x000000000000000000000000000000ab")}],
        ),
    ),
    "take_profit": (
        "take-profit market sell, tpsl tp, positionTpsl, small prices",
        lambda ex: ex.bulk_orders(
            [{"coin": "PUMP", "is_buy": False, "sz": 3569.0, "limit_px": 0.0038,
              "order_type": trig(0.004201, True, "tp"), "reduce_only": True}],
            grouping="positionTpsl",
        ),
    ),
    "entry_with_tpsl": (
        "GTC limit entry plus TP and SL children, grouping normalTpsl",
        lambda ex: ex.bulk_orders(
            [
                {"coin": "BTC", "is_buy": True, "sz": 0.001, "limit_px": 95000.0,
                 "order_type": {"limit": {"tif": "Gtc"}}, "reduce_only": False,
                 "cloid": Cloid.from_str("0x9adf94245f0ec41e000207342a47a439")},
                {"coin": "BTC", "is_buy": False, "sz": 0.001, "limit_px": 99000.0,
                 "order_type": trig(100000.0, True, "tp"), "reduce_only": True},
                {"coin": "BTC", "is_buy": False, "sz": 0.001, "limit_px": 89500.0,
                 "order_type": trig(90000.0, False, "sl"), "reduce_only": True},
            ],
            grouping="normalTpsl",
        ),
    ),
    "update_leverage_cross": (
        "updateLeverage 5x cross",
        lambda ex: ex.update_leverage(5, "HYPE", is_cross=True),
    ),
    "update_leverage_isolated": (
        "updateLeverage 20x isolated",
        lambda ex: ex.update_leverage(20, "ETH", is_cross=False),
    ),
}


def main() -> None:
    cases = []
    for mainnet in (True, False):
        for vault in (VAULT, None):
            for name, (desc, call) in CASES.items():
                captured.clear()
                ex = exchange(mainnet, vault)
                call(ex)
                assert len(captured) == 1, name
                action, sig, nonce = captured[0]
                assert nonce == NONCE
                cid = action_hash(action, vault, nonce, None)
                cases.append({
                    "name": f"{name}/{'mainnet' if mainnet else 'testnet'}/{'vault' if vault else 'novault'}",
                    "desc": desc,
                    "mainnet": mainnet,
                    "action": action,
                    "vault": vault,
                    "nonce": nonce,
                    "connection_id": "0x" + cid.hex(),
                    "signature": sig,
                })
    out = {
        "key": KEY,
        "address": eth_account.Account.from_key(KEY).address,
        "note": "generated by tests/gen_trigger_vectors.py with hyperliquid-python-sdk "
                + importlib.metadata.version("hyperliquid-python-sdk")
                + "; throwaway key, never sent",
        "cases": cases,
    }
    json.dump(out, sys.stdout, indent=1)
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
